/**
 * @param {string} baseText
 * @param {{ classNoun?: string, kind?: 'life'|'current', seed?: number }} opts
 */
export function pickClassFlavoredObjective(baseText, { classNoun, kind = 'life', seed = 0 } = {}) {
  if (!classNoun) return baseText
  const pack = CLASS_FLAVOR[classNoun]
  const pool = pack?.[kind]
  if (!Array.isArray(pool) || !pool.length) {
    return `${baseText} — as ${classNoun}`
  }
  // Mix: prefer class pool, keep base as occasional option for variety
  const mixed = [...pool, baseText]
  const idx = Math.abs(Number(seed) || 0) % mixed.length
  return mixed[idx]
}
